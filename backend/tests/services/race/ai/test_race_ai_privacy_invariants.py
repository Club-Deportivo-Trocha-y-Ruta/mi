class TestSeasonScopeForbiddenNamesIsEmpty:
    """FR-028 / FR-031: when ``forbidden_names=[]`` the name-substitution
    rules are NOT generated (``build_race_v2_forbidden_names_rules`` with an
    empty list returns an empty tuple), so the narrative is expected to already
    be fully anonymous.

    This is the documented contract for *global/season* views that aggregate
    across all athletes and have no single-athlete personal data to protect.
    The LLM receives only a pseudonym; the guardrail receives an empty list
    because there is no specific minor to protect at this aggregate level.
    """

    def test_empty_forbidden_names_generates_no_name_rules(self):
        """``build_race_v2_forbidden_names_rules([])`` returns an empty tuple.

        This is the foundation of the global/season contract: passing an empty
        list MUST produce zero regex rules so the guardrail does not attempt
        name substitution on an underpopulated rule set.
        """
        rules = build_race_v2_forbidden_names_rules([])
        assert rules == (), (
            "build_race_v2_forbidden_names_rules([]) must return () — "
            "no rules generated for the global/season anonymous path."
        )

    def test_guardrails_with_empty_list_does_not_scrub_pseudonym(self):
        """A narrative that uses only pseudonyms passes cleanly when
        ``forbidden_names=[]``.

        Cross-reference: ``test_invariants_v2.py::TestAgeMismatchKwarg`` and
        ``test_guardrails_race_v2_n1.py::TestVetoN1`` already verify veto
        rules; this test specifically validates the name-substitution path
        is correctly a no-op for the empty-list season/global contract.
        """
        g = Guardrails(use_case="race_analyst_v2", forbidden_names=[])
        # Narrative uses only the pseudonym — no real name present.
        clean_text = (
            "## Qué pasó en esta válida\n"
            "La deportista participó con buen ritmo en la categoría infantil.\n\n"
            "## Recorrido hasta acá\n"
            "Con una sola válida disputada aún no es posible establecer "
            "una tendencia de progresión.\n\n"
            "## Hacia dónde va\n"
            "Reforzar técnica de frenada (categoría=technique, prioridad=med) [1].\n"
        )
        report = g.scrub_with_report(clean_text)
        name_violations = [
            v for v in report.violations
            if v.startswith("forbidden_name_")
        ]
        assert name_violations == [], (
            "No forbidden_name_* violations expected when forbidden_names=[].\n"
            f"Got: {name_violations!r}"
        )

    @pytest.mark.asyncio
    async def test_season_summary_with_empty_forbidden_names_succeeds(self, monkeypatch):
        """``invoke_season_summary(forbidden_names=[])`` completes without error.

        Documents that the global/season path explicitly passes an empty list
        (not None) and that this does not trigger any exception or implicit
        name-rule generation.
        """
        import app.services.race.agents.analyst as analyst_mod

        anonymous_text = (
            "## Resumen de temporada\n"
            "La temporada mostró participación activa en la categoría infantil. "
            "La progresión por resultados fue constante.\n"
        )

        async def _fake_call_llm(llm, prompt):
            return _FakeLLMCallResult(anonymous_text)

        monkeypatch.setattr(analyst_mod, "call_llm", _fake_call_llm)
        monkeypatch.setattr(analyst_mod, "build_chat_llm", lambda: None)

        agent = RaceAnalystAgent(prompt_version=PROMPT_VERSION_ANALYST_V2)
        inp = _make_analysis_input(pseudonym="Atleta-0144-T2026")
        # Passing [] explicitly (not None) is the documented global/season contract.
        output, metrics = await agent.invoke_season_summary(
            inp,
            forbidden_names=[],  # empty list = no individual to protect
        )

        assert output is not None
        assert (output.raw_markdown or "") != "", (
            "Season summary must not return empty markdown when anonymous text is clean."
        )
        # No real name in output — sanity check.
        assert not _name_in_text(_SEEDED_MINOR_NAME, output.raw_markdown or "")



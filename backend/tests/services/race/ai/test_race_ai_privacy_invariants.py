def _normalize(text: str) -> str:
    """Lower + strip accents for case/diacritic-insensitive substring check."""
    nfkd = unicodedata.normalize("NFKD", text.lower())
    return "".join(c for c in nfkd if unicodedata.category(c) != "Mn")


def _name_in_text(name: str, text: str) -> bool:
    """True if *name* (or any token of *name* ≥5 chars) appears in *text*."""
    norm_text = _normalize(text)
    for token in name.split():
        if len(token) >= 5 and _normalize(token) in norm_text:
            return True
    # Also check the whole name as a substring.
    return _normalize(name) in norm_text



class TestRoundScopeNameScrubbing:
    """FR-028: round-scope narrative never contains a minor's name.

    Uses a fake ``RaceAnalystAgent`` whose ``invoke_per_valida`` calls the
    real ``_invoke_single_v2`` logic but injects a fake LLM that emits the
    seeded minor's real name. The test asserts that after guardrails the
    ``raw_markdown`` does NOT contain that name.

    We monkey-patch at the ``call_llm`` level inside the agent module so the
    real scrubbing pipeline (guardrails → report) runs unchanged.
    """

    @pytest.mark.asyncio
    async def test_round_narrative_scrubs_forbidden_name(self, monkeypatch):
        """Guardrail removes the minor's name from the round narrative."""
        import app.services.race.agents.analyst as analyst_mod

        dirty_text = _narrative_with_name(_SEEDED_MINOR_NAME)

        async def _fake_call_llm(llm, prompt):
            return _FakeLLMCallResult(dirty_text)

        monkeypatch.setattr(analyst_mod, "call_llm", _fake_call_llm)
        monkeypatch.setattr(analyst_mod, "build_chat_llm", lambda: None)

        agent = RaceAnalystAgent(prompt_version=PROMPT_VERSION_ANALYST_V2)
        inp = _make_analysis_input()
        results = await agent.invoke_per_valida(
            [(1, inp)],
            forbidden_names=[_SEEDED_MINOR_NAME, _SEEDED_MINOR_FULL_NAME],
            is_first_in_season=True,
        )

        output, _ = results[1]
        raw = output.raw_markdown or ""
        assert not _name_in_text(_SEEDED_MINOR_NAME, raw), (
            f"PRIVACY VIOLATION (FR-028, round scope): real minor name "
            f"'{_SEEDED_MINOR_NAME}' still present in narrative after "
            f"guardrails scrubbing.\nraw_markdown={raw!r}"
        )

    @pytest.mark.asyncio
    async def test_round_narrative_pseudonym_still_present_after_scrub(self, monkeypatch):
        """The pseudonym replaces the name — narrative is not empty after scrub."""
        import app.services.race.agents.analyst as analyst_mod

        dirty_text = _narrative_with_name(_SEEDED_MINOR_NAME)

        async def _fake_call_llm(llm, prompt):
            return _FakeLLMCallResult(dirty_text)

        monkeypatch.setattr(analyst_mod, "call_llm", _fake_call_llm)
        monkeypatch.setattr(analyst_mod, "build_chat_llm", lambda: None)

        agent = RaceAnalystAgent(prompt_version=PROMPT_VERSION_ANALYST_V2)
        inp = _make_analysis_input()
        results = await agent.invoke_per_valida(
            [(1, inp)],
            forbidden_names=[_SEEDED_MINOR_NAME],
            is_first_in_season=True,
        )
        output, _ = results[1]
        raw = output.raw_markdown or ""
        # The narrative must still have some content (not blanked out).
        assert len(raw.strip()) > 20, (
            "Narrative was completely wiped after scrubbing — "
            "guardrail should replace with 'la deportista', not blank."
        )

    @pytest.mark.asyncio
    async def test_round_scope_forbidden_names_propagated_from_state(self):
        """``_analyst_agent_v2`` reads ``forbidden_names`` from state and
        passes it to ``invoke_per_valida``.

        Cross-reference: ``test_analyst_agent_v2_uses_full_season.py``
        already verifies this via ``_RecordingAgent``. This test adds the
        assertion at the *guardrail layer*: if the state forbids a name, the
        agent call actually carries it.
        """
        from app.services.race.ai.nodes.analyst_agent import _analyst_agent_v2

        received_forbidden: list[list[str]] = []

        class _SpyAgent:
            async def invoke_per_valida(
                self,
                pairs: list,
                *,
                forbidden_names: list[str] | None = None,
                **kwargs: Any,
            ) -> dict:
                received_forbidden.append(list(forbidden_names or []))
                from tests.services.race.ai.conftest import (
                    make_analysis_output,
                    make_zero_metrics,
                )
                return {
                    vn: (make_analysis_output(), make_zero_metrics("race_analyst_v2"))
                    for vn, _ in pairs
                }

        state = {
            "athlete_id": 1,
            "season": 2026,
            "athlete_age": 13,
            "ltad_group": "juvenil",
            "anonymized_data": {"pseudonym": "AzulZorro"},
            "metrics": {"progression": [{"valida_num": 1, "position": 4}]},
            "podium_context": {},
            "principles": [],
            "memory": [],
            "forbidden_names": [_SEEDED_MINOR_NAME, _SEEDED_MINOR_FULL_NAME],
            "valida_nums": [1],
            "prompt_version": PROMPT_VERSION_ANALYST_V2,
            "is_first_in_season": True,
            "full_season_results": [],
            "_analyst_agent": _SpyAgent(),
        }
        await _analyst_agent_v2(state)

        assert received_forbidden, "invoke_per_valida was never called"
        assert _SEEDED_MINOR_NAME in received_forbidden[0], (
            f"FR-028/FR-031: forbidden_names from state not passed to "
            f"invoke_per_valida. Received: {received_forbidden[0]!r}"
        )



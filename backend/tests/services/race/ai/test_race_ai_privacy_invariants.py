class TestClubScopeParentMasking:
    """FR-028 / FR-030: club-insights response masks names and summary for
    athletes who are NOT the requesting parent's own child.

    The club-insights router does NOT generate new narratives — it reads
    already-persisted per-athlete insights. Privacy is enforced at the router
    layer via ``_build_item_parent_other`` which replaces:
      * ``athlete_display_name`` → "[Atleta del club]"
      * ``summary_excerpt``      → None
      * ``athlete_id``           → 0  (non-navigable)
      * ``confidence``           → None

    This test uses the router helper functions directly (unit level) to avoid
    needing a full HTTP stack, while the integration contract is covered by
    ``test_race_analysis_privacy.py``.
    """

    def test_parent_other_item_does_not_contain_athlete_name(self):
        """``_build_item_parent_other`` produces an item with masked name."""
        from app.routers.club_race_insights import _build_item_parent_other

        item = _build_item_parent_other(athlete_id=42, valida_num=1)

        assert item.athlete_id == 0, (
            "athlete_id must be 0 for other-child parent items "
            "(non-navigable — FR-030)"
        )
        assert "[Atleta" in item.athlete_display_name, (
            "athlete_display_name must be masked for non-child parent items "
            f"(got {item.athlete_display_name!r})"
        )
        assert item.summary_excerpt is None, (
            "summary_excerpt must be None for non-child parent items (FR-028)"
        )
        assert item.confidence is None, (
            "confidence must be None for parent callers (FR-030)"
        )

    def test_parent_other_item_never_contains_real_name(self):
        """The masked item does NOT contain any token of a seeded real name."""
        from app.routers.club_race_insights import _build_item_parent_other

        item = _build_item_parent_other(athlete_id=99, valida_num=2)
        # Serialise all string fields.
        all_text = " ".join(
            str(v) for v in [
                item.athlete_display_name,
                item.summary_excerpt,
            ]
            if v is not None
        )
        assert not _name_in_text(_SEEDED_MINOR_NAME, all_text), (
            f"PRIVACY VIOLATION (FR-028, club scope): real minor name token "
            f"found in parent-masked club item. all_text={all_text!r}"
        )

    def test_coach_item_builds_with_excerpt_and_name(self):
        """Coach item (non-masked) carries the display name and summary excerpt.

        Inverse contract: confirm the masking is only applied for parent role —
        coaches must still receive the data for their coaching work.
        """
        from app.routers.club_race_insights import _build_item_coach
        from app.models.athlete_ai_insight import InsightConfidence
        from datetime import datetime, timezone

        item = _build_item_coach(
            athlete_id=42,
            display_name=_SEEDED_MINOR_FULL_NAME,
            valida_num=1,
            insight_id=10,
            summary_text="Progreso en frenada.",
            generated_at=datetime.now(timezone.utc),
            confidence=InsightConfidence.medium,
        )

        assert item.athlete_display_name == _SEEDED_MINOR_FULL_NAME
        assert item.summary_excerpt is not None
        assert item.confidence is not None



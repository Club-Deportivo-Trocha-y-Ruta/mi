class TestGuardrailForbiddenNamesUnit:
    """Unit tests for the ``forbidden_name_*`` rule produced by
    ``build_race_v2_forbidden_names_rules``.

    Cross-reference: ``test_guardrails_race_v2.py`` has the same contract
    marked xfail with the old API. Here we test the implemented API directly
    (the rules build function + Guardrails class), which is confirmed GREEN in
    ``test_guardrails_race_v2_n1.py``.
    """

    def test_forbidden_name_replaced_by_deportista(self):
        """A real name in the narrative is replaced with 'la deportista'."""
        g = Guardrails(
            use_case="race_analyst_v2",
            forbidden_names=[_SEEDED_MINOR_NAME],
        )
        text = (
            f"## Qué pasó en esta válida\n"
            f"La ciclista {_SEEDED_MINOR_NAME} hizo una gran carrera.\n\n"
            f"## Recorrido hasta acá\n"
            f"Con una sola válida disputada aún no es posible establecer "
            f"una tendencia de progresión.\n\n"
            f"## Hacia dónde va\n"
            f"Continuar entrenando técnica.\n"
        )
        report = g.scrub_with_report(text)

        # After scrubbing, the real name must be absent.
        assert _SEEDED_MINOR_NAME not in report.text, (
            f"Real name '{_SEEDED_MINOR_NAME}' still present after scrub.\n"
            f"scrubbed={report.text!r}"
        )
        # And at least one forbidden_name_* violation was recorded.
        assert any(v.startswith("forbidden_name_") for v in report.violations), (
            f"Expected a forbidden_name_* violation. Got: {report.violations!r}"
        )

    def test_forbidden_name_case_insensitive(self):
        """Name match is case-insensitive (Ley 1581 — no bypass via casing)."""
        g = Guardrails(
            use_case="race_analyst_v2",
            forbidden_names=[_SEEDED_MINOR_NAME],
        )
        text = (
            "## Qué pasó en esta válida\n"
            "VALENTINA compitió bien.\n\n"
            "## Recorrido hasta acá\n"
            "Con una sola válida disputada aún no es posible establecer "
            "una tendencia de progresión.\n\n"
            "## Hacia dónde va\n"
            "Técnica de frenada.\n"
        )
        report = g.scrub_with_report(text)

        assert _SEEDED_MINOR_NAME.upper() not in report.text
        assert "valentina" not in report.text.lower(), (
            "Case-insensitive match failed: uppercase variant still present."
        )

    def test_forbidden_name_empty_list_no_violation(self):
        """``forbidden_names=[]`` produces zero name-substitution rules —
        passing a narrative with a name does NOT trigger a violation.

        This is the documented global/season contract: the caller explicitly
        opts out of per-athlete name protection when processing aggregate data.
        A real name should not appear in an aggregate narrative by construction
        (the prompt only receives pseudonyms), but even if it did, the empty
        list contract means NO name rules are installed.
        """
        g = Guardrails(use_case="race_analyst_v2", forbidden_names=[])
        text = (
            "## Qué pasó en esta válida\n"
            "La deportista participó activamente.\n\n"
            "## Recorrido hasta acá\n"
            "Con una sola válida disputada aún no es posible establecer "
            "una tendencia de progresión.\n\n"
            "## Hacia dónde va\n"
            "Técnica de descenso.\n"
        )
        report = g.scrub_with_report(text)
        name_violations = [v for v in report.violations if v.startswith("forbidden_name_")]
        assert name_violations == [], (
            "With forbidden_names=[], no name-substitution rules should fire.\n"
            f"violations={name_violations!r}"
        )
